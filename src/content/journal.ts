/** Same prompt all day; a new one tomorrow. */
export function promptOfTheDay(d = new Date(), offset = 0): string {
  const day = Math.floor(new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime() / 86_400_000);
  return JOURNAL_PROMPTS[(day + offset) % JOURNAL_PROMPTS.length];
}
