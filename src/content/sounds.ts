export const soundById = (id: string) => SOUNDS.find((s) => s.id === id);

/** Which sound set an IPA phoneme from Azure belongs to (for tracking weak sounds everywhere). */
export function soundForPhoneme(p: string): SoundSet | undefined {
  return SOUNDS.find((s) => s.ipa.length && s.ipa.includes(p) && s.kind !== 'cluster');
}
